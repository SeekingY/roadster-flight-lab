import {mkdir as makeOutputDirectory} from 'node:fs/promises';
await makeOutputDirectory('out',{recursive:true});
import {chromium} from 'playwright';
import {pathToFileURL} from 'node:url';
import {resolve} from 'node:path';
import {writeFile} from 'node:fs/promises';
const round=process.argv[2]||'2';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:900}}),errors=[],warnings=[];
page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error'||m.type()==='warning')warnings.push(m.text())});
await page.goto(pathToFileURL(resolve('roadster.html')).href+'?film=1');await page.waitForFunction(()=>document.documentElement.dataset.ready==='true');
await page.evaluate(()=>{document.body.classList.remove('recording');window.__roadsterTest.setView('exterior')});
const shot=async name=>{await page.screenshot({path:`out/quality-r${round}-${name}.png`});console.log(name)};
await shot('hero');
await page.evaluate(()=>{const a=window.__roadsterTest;a.camera.position.set(3.6,1.12,3.4);a.controls.target.set(5.6,.43,.9);a.camera.lookAt(a.controls.target);a.camera.fov=34;a.camera.updateProjectionMatrix();a.update(0,true)});await shot('wheel');
await page.evaluate(()=>{const a=window.__roadsterTest;a.camera.position.set(13,1.4,4.6);a.controls.target.set(7,.55,0);a.camera.lookAt(a.controls.target);a.camera.fov=34;a.camera.updateProjectionMatrix();a.update(0,true)});await shot('rear');
await page.evaluate(()=>{const a=window.__roadsterTest;a.setMode('flight');a.seek(10)});await shot('vapor');
await page.evaluate(()=>{const a=window.__roadsterTest;a.setMode('kickflip');a.seek(15)});await shot('roll');
await page.getByRole('button',{name:'画质 · 精致',exact:true}).click();
const quality=await page.evaluate(()=>window.__roadsterTest.premium.quality);if(quality!=='balanced')errors.push('quality toggle failed');
await page.evaluate(()=>window.__roadsterTest.setView('exterior'));await shot('balanced');
await page.getByRole('button',{name:'画质 · 流畅',exact:true}).click();
await page.setViewportSize({width:390,height:900});await shot('phone');
const report={round,errors,warnings,qualityToggle:quality,overflow:await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)};
await writeFile(`out/quality-r${round}.json`,JSON.stringify(report,null,2));console.log(JSON.stringify(report));await browser.close();if(errors.length||report.overflow)process.exitCode=1;
